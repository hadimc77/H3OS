static mb2_tag_t* mb2_find(mb2_info_t* info, u32 type) {
    if (!info) return NULL;
    u8* ptr = (u8*)info + 8;
    u8* end = (u8*)info + info->total_size;
    while (ptr < end) {
        mb2_tag_t* tag = (mb2_tag_t*)ptr;
        if (tag->type == MB2_TAG_END) break;
        if (tag->type == type) return tag;
        ptr += (tag->size + 7) & ~7u;
    }
    return NULL;
}

void fb_init(mb2_info_t* mb2) {
    memset(&g_fb, 0, sizeof(g_fb));
    mb2_tag_framebuffer_t* tag =
        (mb2_tag_framebuffer_t*)mb2_find(mb2, MB2_TAG_FRAMEBUFFER);

    if (tag && tag->framebuffer_type == 1 && tag->bpp == 32) {
        g_fb.pixels = (u32*)(uintptr_t)tag->addr;
        g_fb.width  = tag->width;
        g_fb.height = tag->height;
        g_fb.pitch  = tag->pitch;
        g_fb.bpp    = tag->bpp;
        KLOG_INFO("fb", "Framebuffer %ux%u@%u at %p pitch=%u",
                  g_fb.width, g_fb.height, g_fb.bpp,
                  (void*)g_fb.pixels, g_fb.pitch);
    } else {
        /* Text-mode fallback markers — still allocate a synthetic buffer */
        g_fb.width  = 1280;
        g_fb.height = 720;
        g_fb.pitch  = g_fb.width * 4;
        g_fb.bpp    = 32;
        size_t pages = H3OS_ALIGN_UP(g_fb.pitch * g_fb.height, PAGE_SIZE) / PAGE_SIZE;
        phys_addr_t p = pmm_alloc_pages(pages);
        g_fb.pixels = p ? (u32*)(uintptr_t)p : g_fallback;
        KLOG_WARN("fb", "No GOP framebuffer — using software surface %ux%u",
                  g_fb.width, g_fb.height);
    }

    /* Double buffer for tear-free compositing */
    size_t bytes = (size_t)g_fb.pitch * g_fb.height;
    size_t pages = H3OS_ALIGN_UP(bytes, PAGE_SIZE) / PAGE_SIZE;
    phys_addr_t back = pmm_alloc_pages(pages);
    if (back) {
        g_fb.back = (u32*)(uintptr_t)back;
        g_fb.double_buffered = true;
        memset(g_fb.back, 0, bytes);
        KLOG_INFO("fb", "Double buffering enabled");
    } else {
        g_fb.back = g_fb.pixels;
        g_fb.double_buffered = false;
    }
}

fb_t* fb_get(void) { return &g_fb; }

static inline u32* fb_row(i32 y) {
    u32* base = g_fb.double_buffered ? g_fb.back : g_fb.pixels;
    return (u32*)((u8*)base + (size_t)y * g_fb.pitch);
}

void fb_put_pixel(i32 x, i32 y, u32 color) {
    if ((u32)x >= g_fb.width || (u32)y >= g_fb.height) return;
    fb_row(y)[x] = color;
}

u32 fb_get_pixel(i32 x, i32 y) {
    if ((u32)x >= g_fb.width || (u32)y >= g_fb.height) return 0;
    return fb_row(y)[x];
}

void fb_clear(u32 color) {
    for (u32 y = 0; y < g_fb.height; y++) {
        u32* row = fb_row((i32)y);
        for (u32 x = 0; x < g_fb.width; x++) row[x] = color;
    }
}

void fb_fill_rect(i32 x, i32 y, i32 w, i32 h, u32 color) {
    for (i32 j = 0; j < h; j++) {
        for (i32 i = 0; i < w; i++) {
            fb_put_pixel(x + i, y + j, color);
        }
    }
}

void fb_draw_rect(i32 x, i32 y, i32 w, i32 h, u32 color) {
    for (i32 i = 0; i < w; i++) {
        fb_put_pixel(x + i, y, color);
        fb_put_pixel(x + i, y + h - 1, color);
    }
    for (i32 j = 0; j < h; j++) {
        fb_put_pixel(x, y + j, color);
        fb_put_pixel(x + w - 1, y + j, color);
    }
}

void fb_draw_line(i32 x0, i32 y0, i32 x1, i32 y1, u32 color) {
    i32 dx = (x1 > x0) ? x1 - x0 : x0 - x1;
    i32 sx = x0 < x1 ? 1 : -1;
    i32 dy = (y1 > y0) ? y0 - y1 : y1 - y0;
    i32 sy = y0 < y1 ? 1 : -1;
    i32 err = dx + dy;
    for (;;) {
        fb_put_pixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        i32 e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

static bool in_rounded_corner(i32 px, i32 py, i32 x, i32 y, i32 w, i32 h, i32 r) {
    i32 cx, cy;
    if (px < x + r && py < y + r) { cx = x + r; cy = y + r; }
    else if (px >= x + w - r && py < y + r) { cx = x + w - r - 1; cy = y + r; }
    else if (px < x + r && py >= y + h - r) { cx = x + r; cy = y + h - r - 1; }
    else if (px >= x + w - r && py >= y + h - r) { cx = x + w - r - 1; cy = y + h - r - 1; }
    else return true;
    i32 dx = px - cx, dy = py - cy;
    return dx * dx + dy * dy <= r * r;
}

void fb_fill_rounded_rect(i32 x, i32 y, i32 w, i32 h, i32 r, u32 color) {
    if (r <= 0) { fb_fill_rect(x, y, w, h, color); return; }
    for (i32 j = 0; j < h; j++) {
        for (i32 i = 0; i < w; i++) {
            if (in_rounded_corner(x + i, y + j, x, y, w, h, r))
                fb_put_pixel(x + i, y + j, color);
        }
    }
}

void fb_draw_rounded_rect(i32 x, i32 y, i32 w, i32 h, i32 r, u32 color) {
    fb_draw_rect(x, y, w, h, color);
    H3OS_UNUSED(r);
}

void fb_blit(i32 x, i32 y, i32 w, i32 h, const u32* src, i32 src_stride) {
    for (i32 j = 0; j < h; j++) {
        for (i32 i = 0; i < w; i++) {
            fb_put_pixel(x + i, y + j, src[j * src_stride + i]);
        }
    }
}

void fb_draw_char(i32 x, i32 y, char c, u32 fg, u32 bg) {
    if ((u8)c < 32 || (u8)c > 127) c = '?';
    const u8* glyph = font8x8_basic[(u8)c - 32];
    for (i32 row = 0; row < 8; row++) {
        u8 bits = glyph[row];
        for (i32 col = 0; col < 8; col++) {
            u32 color = (bits & (1 << col)) ? fg : bg;
            if (bg != 0xFFFFFFFF || (bits & (1 << col)))
                fb_put_pixel(x + col, y + row, color);
        }
    }
}

void fb_draw_string(i32 x, i32 y, const char* s, u32 fg, u32 bg) {
    i32 cx = x;
    while (*s) {
        if (*s == '\n') { cx = x; y += 10; s++; continue; }
        fb_draw_char(cx, y, *s++, fg, bg);
        cx += 8;
    }
}

void fb_swap(void) {
    if (!g_fb.double_buffered) return;
    u8* dst = (u8*)g_fb.pixels;
    u8* src = (u8*)g_fb.back;
    size_t bytes = (size_t)g_fb.pitch * g_fb.height;
    memcpy(dst, src, bytes);
}
